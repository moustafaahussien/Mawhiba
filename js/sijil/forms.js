/* ===================== محرك التصحيح ===================== */
const LEVEL_TEXT = { high: 'عالٍ', mid: 'متوسط', low: 'منخفض', none: 'لا دلالة' };

function getForm(id) { return FORMS.find(f => f.id === id); }

function itemText(it) { return typeof it === 'string' ? it : it.t; }

/* قائمة البنود مرقّمة تسلسلياً على مستوى النموذج كله */
function flatItems(form) {
  const out = []; let n = 0;
  form.sections.forEach(s => s.items.forEach(it => { n++; out.push({ n, section: s.id, text: itemText(it), tag: it.tag || '', o: it.o || null, rev: (form.rev || []).includes(n) }); }));
  return out;
}

/* أعلى درجة ممكنة للنموذج كاملاً */
function formMax(form) { return flatItems(form).length * Math.max(...SCALES[form.scale].values); }

/* وصف نطاقات أسلوب التفكير بالكلمات */
function describeStyleBands(form) {
  const bands = form.scoring.bands, max = formMax(form);
  return bands.map((bd, i) => {
    const hi = i === 0 ? max : bands[i - 1].min - 1;
    const range = bd.min === 0 ? `${hi} فأقل` : hi === bd.min ? `${hi}` : i === 0 ? `${bd.min} فأكثر` : `من ${bd.min} إلى ${hi}`;
    if (!bd.st) return `${range} = لا دلالة`;
    const names = STYLE_NAMES[bd.st] + (bd.also ? ' / ' + STYLE_NAMES[bd.also] : '');
    return `${range} = ${names} (${PREF_TEXT[bd.p]})`;
  }).join('، ');
}

function styleOf(form, value) {
  const bd = band(value, form.scoring.bands);
  if (!bd.st) return { st: '', also: '', pref: -1, level: 'none', label: 'لا دلالة' };
  return {
    st: bd.st, also: bd.also, pref: bd.p,
    level: bd.p === 1 ? 'high' : bd.p === 2 ? 'mid' : 'low',
    label: STYLE_NAMES[bd.st] + (bd.also ? ' / ' + STYLE_NAMES[bd.also] : '') + ' — ' + PREF_TEXT[bd.p]
  };
}

function band(value, bands) {
  const v = Math.round(value * 100) / 100;
  return bands.find(b => v >= b.min) || bands[bands.length - 1];
}

/* answers: { "1": 4, "2": 3, ... } بترقيم تسلسلي */
function scoreForm(form, answers) {
  const sc = form.scoring, items = flatItems(form);
  const val = n => Number(answers[n] || 0);
  const r2 = x => Math.round(x * 100) / 100;
  const res = { parts: [], summary: '' };

  if (sc.kind === 'sectionSum') {
    const max = Math.max(...SCALES[form.scale].values);
    form.sections.forEach(s => {
      const its = items.filter(i => i.section === s.id);
      const sum = its.reduce((a, i) => a + val(i.n), 0);
      const b = band(sum, sc.bands[s.id]);
      res.parts.push({ id: s.id, title: s.title.replace(/^[أ-ي]\s*–\s*/, ''), score: sum, max: its.length * max, level: b.level, label: b.label });
    });
    res.summary = res.parts.map(p => `${p.title}: ${p.score}/${p.max} (${p.label})`).join(' | ');
  }

  if (sc.kind === 'mean') {
    const sum = items.reduce((a, i) => a + val(i.n), 0);
    const mean = r2(sum / items.length);
    const b = band(mean, sc.bands);
    res.parts.push({ id: 'mean', title: form.short, score: mean, sum, max: sc.max, level: b.level, label: b.label });
    res.summary = `مجموع النقاط ${sum}، المتوسط ${mean} من ${sc.max} (${b.label})`;
  }

  if (sc.kind === 'groups') {
    sc.groups.forEach(g => {
      const sum = g.items.reduce((a, n) => a + val(n), 0);
      const mean = r2(sum / g.items.length);
      const b = band(mean, sc.bands);
      res.parts.push({ id: g.id, title: g.title, score: mean, sum, count: g.items.length, max: sc.max, level: b.level, label: b.label });
    });
    const strong = res.parts.filter(p => p.level === 'high').map(p => p.title);
    const pref = res.parts.filter(p => p.level === 'mid').map(p => p.title);
    res.summary = (strong.length ? 'مفضل بقوة: ' + strong.join('، ') : 'لا يوجد نشاط مفضل بقوة') +
                  (pref.length ? ' | مفضل: ' + pref.join('، ') : '');
  }

  if (sc.kind === 'style') {
    const vals = SCALES[form.scale].values, hi = Math.max(...vals), lo = Math.min(...vals);
    const sum = items.reduce((a, i) => a + (i.n in answers ? (i.rev ? hi + lo - val(i.n) : val(i.n)) : 0), 0);
    const s = styleOf(form, sum), max = formMax(form);
    res.parts.push({ id: 'style', title: form.short, score: sum, max, level: s.level, label: s.label, st: s.st, also: s.also, pref: s.pref });
    res.summary = `المجموع ${sum} من ${max} — ` + (s.st ? 'يدل على الأسلوب ' + s.label : 'لا دلالة على أسلوب محدد');
  }

  if (sc.kind === 'rank') {
    items.forEach(i => res.parts.push({ id: 'i' + i.n, title: i.tag, product: i.text, score: val(i.n), max: sc.max,
      level: val(i.n) >= 5 ? 'high' : val(i.n) >= 4 ? 'mid' : 'low', label: SCALES[form.scale].labels[val(i.n)] || '' }));
    const top = Math.max(...res.parts.map(p => p.score));
    const best = res.parts.filter(p => p.score === top);
    res.summary = 'الأسلوب المفضل: ' + best.map(p => `${p.title} (${p.product})`).join('، ') + ` — بدرجة ${top} من 5`;
  }
  return res;
}

